async function regularInput(root, relative) {
  let current = root;
  const parts = relative.split('/');
  for (let i=0;i<parts.length;i++) {
    current=join(current,parts[i]);
    const info=await lstat(current);
    if(info.isSymbolicLink() || (i===parts.length-1 ? !info.isFile() : !info.isDirectory()))
      throw Error('Guest input must be a regular file without symlinks: ' + relative);
  }
  return current;
}
async function safeOutput(root) {
  const dist=join(root,'dist');
  const info=await lstat(dist).catch(e=>{if(e.code!=='ENOENT')throw e;});
  if(info&&(!info.isDirectory()||info.isSymbolicLink())) throw Error('dist must be a regular directory');
  await mkdir(dist,{recursive:true});
  const output=join(dist,'guest-preview');
  const old=await lstat(output).catch(e=>{if(e.code!=='ENOENT')throw e;});
  if(old&&(!old.isDirectory()||old.isSymbolicLink())) throw Error('Guest output must be a regular directory');
  return {dist,output};
}
