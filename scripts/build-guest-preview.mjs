export async function verifyGuest(root=ROOT) {
  root=resolve(root);
  const dist=join(root,'dist');
  const distInfo=await lstat(dist);
  if(!distInfo.isDirectory()||distInfo.isSymbolicLink()) throw Error('dist must be a regular directory');
  const output=join(dist,'guest-preview');
  const info=await lstat(output);
  if(!info.isDirectory()||info.isSymbolicLink()) throw Error('Guest output must be a regular directory');
  for(const name of ['wrangler.toml','guest-manifest.json']) {
    const metadata=await lstat(join(output,name));
    if(!metadata.isFile()||metadata.isSymbolicLink()) throw Error('Guest metadata must be a regular file: '+name);
  }
  const nested=await lstat(join(output,'dist'));
  if(!nested.isDirectory()||nested.isSymbolicLink()) throw Error('Guest dist parent must be a regular directory');
  const config=await readFile(join(output,'wrangler.toml'),'utf8');
  if(config!==WRANGLER) throw Error('Guest Wrangler config mismatch');
  for(const file of ['index.html','mock-exam-editor.html','document-editor.html','service-config.js','assets/index-3.js','assets/mock-exam-editor-1.js','assets/document-editor-1.js'])
    checkGuestPolicy(file,await readFile(join(output,'dist/public',file)));
  const manifest=await verifyPublic(join(output,'dist/public'));
  const saved=JSON.parse(await readFile(join(output,'guest-manifest.json'),'utf8'));
  if(saved.kind!=='guest-preview'||JSON.stringify(saved.files)!==JSON.stringify(manifest)) throw Error('Guest manifest mismatch');
  for(const file of Object.keys(manifest).filter(f=>/\.(?:html|js|mjs|css)$/.test(f)))
    checkGuestPolicy(file,await readFile(join(output,'dist/public',file)));
  return manifest;
}
export async function buildGuest(root=ROOT) {
  root=resolve(root);
  const rootInfo=await lstat(root);
  if(!rootInfo.isDirectory()||rootInfo.isSymbolicLink()) throw Error('Guest source root must be a regular directory');
  const original=new Map();
  for(const file of PUBLIC_INPUTS) original.set(file,await readFile(await regularInput(root,file)));
  const {dist,output}=await safeOutput(root);
  const staging=await mkdtemp(join(dist,'.guest-input-'));
  const publish=await mkdtemp(join(dist,'.guest-output-'));
  try {
    for(const [file,bytes] of original) {
      const dest=join(staging,file);
      await mkdir(dirname(dest),{recursive:true});
      await writeFile(dest,transform(file,bytes));
    }
    const manifest=await buildPublic(staging);
    for(const [file,bytes] of original) {
      const after=await readFile(await regularInput(root,file));
      if(!after.equals(bytes)) throw Error('Guest build changed a source input: '+file);
    }
    await mkdir(join(publish,'dist'),{recursive:true});
    await rename(join(staging,'dist/public'),join(publish,'dist/public'));
    await writeFile(join(publish,'guest-manifest.json'),JSON.stringify({kind:'guest-preview',files:manifest},null,2)+'\n');
    await writeFile(join(publish,'wrangler.toml'),WRANGLER);
    for(const file of Object.keys(manifest).filter(f=>/\.(?:html|js|mjs|css)$/.test(f)))
      checkGuestPolicy(file,await readFile(join(publish,'dist/public',file)));
    const old=await lstat(output).catch(e=>{if(e.code!=='ENOENT')throw e;});
    if(old&&(!old.isDirectory()||old.isSymbolicLink())) throw Error('Guest output is unsafe');
    await rm(output,{recursive:true,force:true});
    await rename(publish,output);
    await verifyGuest(root);
    return manifest;
  } finally {
    await rm(staging,{recursive:true,force:true});
    await rm(publish,{recursive:true,force:true});
  }
}
