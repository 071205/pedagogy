function exact(source, before, after, label) {
  const count = source.split(before).length - 1;
  if (count !== 1) throw Error('Guest transform anchor mismatch: ' + label + ' (' + count + ')');
  return source.replace(before, after);
}
function exactRegex(source, expression, after, label) {
  const matches = [...source.matchAll(new RegExp(expression.source, expression.flags.includes('g') ? expression.flags : expression.flags + 'g'))];
  if (matches.length !== 1) throw Error('Guest transform anchor mismatch: ' + label + ' (' + matches.length + ')');
  return source.replace(expression, after);
}
function policy(source, file) {
  return exactRegex(source, /(<meta\s+http-equiv="Content-Security-Policy"\s+content=")([\s\S]*?)(")/i,
    (_whole, open, value, close) => {
      const directives = value.split(';').map(v => v.trim()).filter(Boolean);
      const keep = directives.filter(v => !/^(script-src|connect-src|font-src|img-src|frame-src)\s/.test(v));
      const script = file === 'index.html' ? "script-src 'self' 'wasm-unsafe-eval' https://cdn.jsdelivr.net" : "script-src 'self' https://cdn.jsdelivr.net";
      const font = "font-src 'self' data: https://cdn.jsdelivr.net";
      const img = "img-src 'self' data: blob:";
      const connect = "connect-src 'self'";
      const frame = file === 'index.html' ? "frame-src 'self'" : '';
      return open + [keep[0], script, ...keep.slice(1), font, img, connect, ...(frame ? [frame] : [])].join('; ') + close;
    }, file + ' CSP');
}
