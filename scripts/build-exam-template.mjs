// Classic script fallback for file://; the HWPX file remains the source of truth.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const src=readFileSync('experiments/hwp-export/templates/exam-math.hwpx');
const out='// Generated by scripts/build-exam-template.mjs; do not edit.\nwindow.PEDAGOGY_EXAM_TEMPLATE_BASE64 = '+JSON.stringify(src.toString('base64'))+';\n';
if(process.argv.includes('--check'))assert.equal(readFileSync('exam-template-data.js','utf8'),out);
else writeFileSync('exam-template-data.js',out);
