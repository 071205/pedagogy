/* HWPX 틀을 고전 스크립트로 인라인한다 — `file://` 에서 fetch 가 막히기 때문이다.
 *
 * ⚠️ **`.hwpx` 파일이 계속 정답표다.** 이 생성물은 사본이므로 `--check` 로 낡음을 잡는다
 * (`test:review-contracts` 안에서 돈다). 원본 틀을 바꿨으면 이 스크립트를 다시 돌린다.
 *
 * ⚠️ 두 틀을 한 표로 다룬다 — 예전에는 시험지 틀만 있었고, 빈 문서 골격을 위해 스크립트를
 * 하나 더 만들면 **베낀 것이 갈라진다.** 새 틀이 생기면 `TEMPLATES` 에 한 줄만 더한다.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const TEMPLATES = [
  {
    source: 'experiments/hwp-export/templates/exam-math.hwpx',
    out: 'exam-template-data.js',
    global: 'PEDAGOGY_EXAM_TEMPLATE_BASE64',
  },
  {
    source: 'experiments/hwp-export/templates/blank.hwpx',
    out: 'blank-template-data.js',
    global: 'PEDAGOGY_BLANK_TEMPLATE_BASE64',
  },
];

const render = ({ source, global: name }) =>
  '// Generated by scripts/build-hwpx-templates.mjs; do not edit.\n'
  + '// Source: ' + source + '\n'
  + 'window.' + name + ' = ' + JSON.stringify(readFileSync(source).toString('base64')) + ';\n';

const check = process.argv.includes('--check');
for (const template of TEMPLATES) {
  const text = render(template);
  if (check) assert.equal(readFileSync(template.out, 'utf8'), text,
    template.out + ' 가 ' + template.source + ' 보다 낡았습니다 — node scripts/build-hwpx-templates.mjs');
  else writeFileSync(template.out, text);
}
console.log((check ? '틀 인라인 최신 확인' : '틀 인라인 생성')
  + ' — ' + TEMPLATES.map((t) => t.out).join(' · '));
